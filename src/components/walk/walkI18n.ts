export function getWalkFeedbackLabel(id: WalkFeedbackId, language: Language) {
  return feedbackLabels[id]?.[language] ?? id;
}

export function getWalkFeedbackSummaryText(ids: WalkFeedbackId[], language: Language) {
  if (ids.length === 0) return walkUiText[language].feedbackDefault;
  return ids.map((id) => getWalkFeedbackLabel(id, language)).join(" / ");
}
